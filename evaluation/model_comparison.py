"""
evaluation/model_comparison.py
================================
Generates the benchmark comparison table in LaTeX format.

Produces:
  report/figures/models/benchmark_table.tex  -- \input{}-able LaTeX table
  models/benchmark_summary.json              -- for dashboard display

Table columns:
  Model | AUPRC [95% CI] | AUROC [95% CI] | Precision | Recall | F1 | MCC | Brier | Cost/txn | theta*

Statistical annotations:
  Best value in each column shown in \textbf{}
  Wilcoxon p-value shown in table caption
"""
from __future__ import annotations

import json
import logging
from pathlib import Path

import numpy as np

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)s | %(message)s",
)
log = logging.getLogger(__name__)

ROOT = Path(__file__).parent.parent
MODELS_DIR = ROOT / "models"
FIG_DIR = ROOT / "report" / "figures" / "models"
FIG_DIR.mkdir(parents=True, exist_ok=True)

MODEL_ORDER = ["Logistic Regression", "XGBoost", "Isolation Forest", "Autoencoder"]

# Map metric name -> "higher is better" (True) or "lower is better" (False)
METRIC_DIRECTION = {
    "auprc":            True,
    "auroc":            True,
    "precision":        True,
    "recall":           True,
    "f1":               True,
    "mcc":              True,
    "brier":            False,
    "exp_cost_per_txn": False,
}


def _bold(val: str, is_best: bool) -> str:
    return f"\\textbf{{{val}}}" if is_best else val


def generate_latex_table(version: int = 1) -> str:
    """
    Generate a complete LaTeX longtable for the benchmark comparison.

    Returns
    -------
    str : Complete LaTeX table string (ready for \input{}).
    """
    metrics_path = MODELS_DIR / "all_metrics.json"
    if not metrics_path.exists():
        raise FileNotFoundError(f"Run evaluation/metrics.py first: {metrics_path} not found")

    all_metrics = json.loads(metrics_path.read_text())
    wilcoxon_path = MODELS_DIR / "wilcoxon_test.json"
    wilcoxon = json.loads(wilcoxon_path.read_text()) if wilcoxon_path.exists() else {}

    # Determine best value for each scalar metric
    best_vals = {}
    for metric, higher_is_better in METRIC_DIRECTION.items():
        vals = {
            name: m[metric]
            for name, m in all_metrics.items()
            if metric in m
        }
        if not vals:
            continue
        best_vals[metric] = max(vals, key=vals.get) if higher_is_better else min(vals, key=vals.get)

    # Build table rows
    rows = []
    for model_name in MODEL_ORDER:
        if model_name not in all_metrics:
            continue
        m = all_metrics[model_name]
        sup_tag = "(S)" if m.get("supervised", False) else "(U)"

        def fmt(key: str, decimals: int = 3) -> str:
            if key not in m:
                return "---"
            val = m[key]
            formatted = f"{val:.{decimals}f}"
            return _bold(formatted, best_vals.get(key) == model_name)

        def fmt_ci(key: str, lo_key: str, hi_key: str) -> str:
            if key not in m:
                return "---"
            val = f"{m[key]:.3f}"
            lo  = f"{m.get(lo_key, 0):.3f}"
            hi  = f"{m.get(hi_key, 0):.3f}"
            core = f"{val} [{lo}, {hi}]"
            return _bold(core, best_vals.get(key) == model_name)

        row = (
            f"        {model_name} {sup_tag} & "
            f"{fmt_ci('auprc', 'auprc_ci_lo', 'auprc_ci_hi')} & "
            f"{fmt_ci('auroc', 'auroc_ci_lo', 'auroc_ci_hi')} & "
            f"{fmt('precision')} & "
            f"{fmt('recall')} & "
            f"{fmt('f1')} & "
            f"{fmt('mcc')} & "
            f"{fmt('brier', 4)} & "
            f"{fmt('exp_cost_per_txn', 4)} & "
            f"$ \\\\"
        )
        rows.append(row)

    wilcoxon_caption = ""
    if wilcoxon:
        p = wilcoxon.get("p_value", 1.0)
        ma = wilcoxon.get("model_A", "")
        mb = wilcoxon.get("model_B", "")
        sig = "significant" if p < 0.05 else "not significant"
        wilcoxon_caption = (
            f"Wilcoxon signed-rank test ({ma} vs.~{mb}): "
            f" = {p:.4f}$ ({sig} at $\\alpha=0.05$). "
        )

    table_str = r"""% Auto-generated by evaluation/model_comparison.py — do not edit manually.
% Compiled with: pdflatex -> biber -> pdflatex -> pdflatex
\begin{table}[htbp]
  \centering
  \caption{Benchmark comparison of fraud detection models on the IEEE-CIS test set (20\% stratified split).
           All metrics are computed at the cost-optimal threshold $\theta^*$ ({FP}=\$, {FN}=\$).
           AUPRC and AUROC reported with 95\% bootstrap confidence intervals (=1{,}000$ resamples).
           (S) = supervised; (U) = unsupervised. """ + wilcoxon_caption + r"""
           \textbf{Bold} indicates best value per column.}
  \label{tab:model_comparison}
  \small
  \begin{tabular}{lccccccccc}
    \toprule
    \textbf{Model} &
    \textbf{AUPRC [95\% CI]} &
    \textbf{AUROC [95\% CI]} &
    \textbf{Prec.} &
    \textbf{Recall} &
    \textbf{F1} &
    \textbf{MCC} &
    \textbf{Brier} &
    \textbf{Cost/txn (\$)} &
    \textbf{$\theta^*$} \\
    \midrule
""" + "\n".join(rows) + r"""
    \bottomrule
  \end{tabular}
\end{table}
"""
    return table_str


def run_model_comparison(version: int = 1) -> None:
    """Generate LaTeX table and benchmark summary JSON."""
    log.info("Generating benchmark comparison table...")

    latex_table = generate_latex_table(version)

    # Save LaTeX table
    table_path = FIG_DIR / "benchmark_table.tex"
    table_path.write_text(latex_table)
    log.info(f"LaTeX table saved -> {table_path}")

    # Also save a summary JSON for the Streamlit dashboard
    metrics_path = MODELS_DIR / "all_metrics.json"
    if metrics_path.exists():
        all_metrics = json.loads(metrics_path.read_text())
        summary = []
        for name in MODEL_ORDER:
            if name in all_metrics:
                m = all_metrics[name]
                summary.append({
                    "Model":    name,
                    "Type":     "Supervised" if m.get("supervised") else "Unsupervised",
                    "AUPRC":    m.get("auprc"),
                    "AUROC":    m.get("auroc"),
                    "F1":       m.get("f1"),
                    "MCC":      m.get("mcc"),
                    "Brier":    m.get("brier"),
                    "Cost/txn": m.get("exp_cost_per_txn"),
                    "theta*":   m.get("threshold"),
                    "AUPRC_CI": f"[{m.get('auprc_ci_lo')}, {m.get('auprc_ci_hi')}]",
                })
        summary_path = MODELS_DIR / "benchmark_summary.json"
        summary_path.write_text(json.dumps(summary, indent=2))
        log.info(f"Benchmark summary saved -> {summary_path}")

    log.info("\nPreview of LaTeX table:\n")
    log.info(latex_table[:800] + "...\n")


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--version", type=int, default=1)
    args = parser.parse_args()
    run_model_comparison(version=args.version)
